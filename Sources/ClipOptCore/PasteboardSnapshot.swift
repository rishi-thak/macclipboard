import AppKit

/// An exact copy of everything on a pasteboard: every item, every type, every byte.
///
/// Smart paste briefly puts text on the clipboard to send Cmd+V. Restoring from a
/// snapshot afterwards means an image (PNG, TIFF), file, or rich text you had
/// copied comes back untouched, so a normal Cmd+V still pastes it like stock macOS.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Entry: Sendable, Equatable {
        public let type: String
        public let data: Data
    }

    /// One inner array per pasteboard item, types in their original order.
    public let items: [[Entry]]

    public init(items: [[Entry]]) {
        self.items = items
    }

    public var isEmpty: Bool { items.isEmpty }

    public static func capture(_ pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type -> Entry? in
                guard let data = item.data(forType: type) else { return nil }
                return Entry(type: type.rawValue, data: data)
            }
        }
        return PasteboardSnapshot(items: items.filter { !$0.isEmpty })
    }

    /// Writes the snapshot back. Returns the pasteboard's new change count.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let pasteboardItems = items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries {
                item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return item
        }
        if !pasteboardItems.isEmpty {
            pasteboard.writeObjects(pasteboardItems)
        }
        return pasteboard.changeCount
    }
}

/// Marker types from nspasteboard.org that clipboard tools agree on.
public enum PasteboardMarkers {
    /// Password managers set these. We never store or send such copies.
    public static let skip: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    /// Added to our own temporary paste so other clipboard tools ignore it too.
    public static let transient = "org.nspasteboard.TransientType"

    /// Copies that aren't plain text (history is text only).
    public static let nonText: Set<String> = [
        "public.png", "public.tiff", "public.jpeg", "public.heic", "public.file-url",
        "com.compuserve.gif", "com.adobe.pdf",
    ]
}
